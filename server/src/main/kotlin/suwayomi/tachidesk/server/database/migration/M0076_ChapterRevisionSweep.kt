        ALTER TABLE chapterrevision ADD COLUMN compared_at BIGINT NULL;
        ALTER TABLE chapterrevision ADD COLUMN comparison_error VARCHAR(1024) NULL;
        -- when the staged pages of an EXACT_MATCH revision may be removed; null while unscheduled
        ALTER TABLE chapterrevision ADD COLUMN comparison_cleanup_due_at BIGINT NULL;

        -- the exactly-one-candidate binding of a sweep item; null for every other discovery
        ALTER TABLE chapterrevision ADD COLUMN sweep_item INT NULL;

        CREATE UNIQUE INDEX chapter_revision_sweep_item_idx ON chapterrevision (sweep_item);
        -- the comparison audit is browsed per state, and a baseline that is pruned must null the
        -- reference instead of deleting the comparison that used it
        CREATE INDEX chapter_revision_comparison_state_idx ON chapterrevision (comparison_state, id);
        -- the cleanup backlog is claimed by its persisted due time
        CREATE INDEX chapter_revision_comparison_cleanup_idx ON chapterrevision (comparison_cleanup_due_at, id);
        ALTER TABLE chapterrevision ADD CONSTRAINT FK_CHAPTERREVISION_COMPARISONBASELINE__ID
            FOREIGN KEY (comparison_baseline_revision) REFERENCES chapterrevision(ID)
            ON DELETE SET NULL ON UPDATE RESTRICT;
        ALTER TABLE chapterrevision ADD CONSTRAINT FK_CHAPTERREVISION_SWEEPITEM__ID
            FOREIGN KEY (sweep_item) REFERENCES chapterrevisionsweepitem(ID)
            ON DELETE SET NULL ON UPDATE RESTRICT;
        """.trimIndent()
}
