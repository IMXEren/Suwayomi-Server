            series_title VARCHAR(512) NOT NULL,
            chapter_name VARCHAR(512) NOT NULL,
            source_chapter_url VARCHAR(2048) NOT NULL,
            -- the acquisition policy resolved for this item when the session started
            policy VARCHAR(64) NOT NULL,
            state VARCHAR(64) NOT NULL DEFAULT '${ChapterRevisionSweepItemState.PENDING.name}',
            attempts INT NOT NULL DEFAULT 0,
            last_error VARCHAR(1024) NULL,
            candidate_count INT NULL,
            -- earliest instant this item may be retried, null while it is due immediately
            due_at BIGINT NULL,
            started_at BIGINT NULL,
            finished_at BIGINT NULL,
            updated_at BIGINT NOT NULL,
            CONSTRAINT FK_CHAPTERREVISIONSWEEPITEM_SESSION__ID
                FOREIGN KEY (session) REFERENCES chapterrevisionsweepsession(ID)
                ON DELETE CASCADE ON UPDATE RESTRICT
        );

        -- the worker claims the earliest claimable item of one session, ordered by its own due time
        CREATE INDEX chapter_revision_sweep_item_backlog_idx ON chapterrevisionsweepitem (session, state, due_at, id);
        -- the per-session item listing is ordered by id and filtered only by session
        CREATE INDEX chapter_revision_sweep_item_session_idx ON chapterrevisionsweepitem (session, id);

