            -- while no retry is pending. `next_due_at` deliberately stays where it is, so a backoff
            -- defers when the occurrence is retried without ever consuming or skipping it.
            retry_not_before BIGINT NULL,
            updated_at BIGINT NOT NULL,
            CONSTRAINT CHK_CHAPTERREVISIONSWEEPSCHEDULE_SINGLETON CHECK (id = 1)
        );

        -- the independent content-comparison dimension of a revision
        --
        -- The default is NOT_EVALUATED, not PENDING: a row that already existed when this migration
        -- runs was never compared, and `ADD COLUMN ... NOT NULL DEFAULT` hands it that value in both
        -- dialects. PENDING means a comparison is still owed, which is only ever true of a candidate
        -- recorded after the dimension existed, and every creation path writes it explicitly.
        ALTER TABLE chapterrevision ADD COLUMN comparison_state VARCHAR(64) NOT NULL DEFAULT '${ChapterRevisionComparisonState.NOT_EVALUATED.name}';
